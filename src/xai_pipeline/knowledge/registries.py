def formula_execution_branch(formula_id: str) -> str:
    """Return the deterministic execution branch that should own a formula."""

    if formula_id in SPATIAL_VECTOR_FORMULA_IDS:
        return "spatial_vector"
    if formula_id in TOPOLOGY_FORMULA_IDS:
        return "topology"
    if formula_id in ALGEBRAIC_SYSTEM_FORMULA_IDS:
        return "algebraic_system"
    if formula_id in {"conceptual_direct", "yes_no_direct"}:
        return "logic"
    if formula_id == "multi_output_direct":
        return "multi_output"
    if formula_id in {"measurement_error_direct", "measurement_absolute_error", "measurement_average"}:
        return "measurement"
    return "scalar_equation"


