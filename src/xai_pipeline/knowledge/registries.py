def formula_family_for_id(formula_id: str) -> str | None:
    for family_id, family in FORMULA_FAMILY_REGISTRY.items():
        if formula_id in family.formula_ids:
            return family_id
    return None


@lru_cache(maxsize=1)
def formula_logic_catalog() -> dict:
    """Return grouped, domain-level formula governance metadata for prompts and audits."""

    families = {}
    covered: set[str] = set()
    for family_id, family in FORMULA_FAMILY_REGISTRY.items():
        executable_formula_ids = [formula_id for formula_id in family.formula_ids if formula_id in FORMULA_IDS]
        covered.update(executable_formula_ids)
        families[family_id] = {
            "domain": family.domain,
            "title": family.title,
            "principle_ids": list(family.principle_ids),
            "task_types": list(family.task_types),
            "formula_ids": executable_formula_ids,
            "execution_branches": sorted({formula_execution_branch(formula_id) for formula_id in executable_formula_ids}),
            "plan_logic": family.plan_logic,
        }
    uncovered = sorted(formula_id for formula_id in FORMULA_IDS if formula_id not in covered)
    return {
        "families": families,
        "uncovered_formula_ids": uncovered,
        "policy": "Formula IDs are grouped by reusable physical law families, not by dataset examples.",
    }


PATTERN_SHAPED_REGISTRY_CUES: FrozenSet[str] = frozenset(
    {
        "dataset row",
        "training example",
        "benchmark item",
    }
)

DATASET_ROW_ID_PATTERN = re.compile(r"\b(?:TD|DDT|THCB|LD|CH|NL|DT|CHLT)\d+\b", flags=re.IGNORECASE)
AMBIGUOUS_EXECUTABLE_EXPRESSION_CUES: FrozenSet[str] = frozenset({" or "})


def audit_registry_generalization() -> dict:
    """Return governance issues for formula cards that look dataset-shaped.

    The registry is allowed to encode physical principles and formula families,
    not one-off problem patterns. This audit is deterministic and intentionally
    lexical; suspicious cards must be rewritten as general constraints before
    they can live in the runtime registry.
    """

    issues = []
    for formula_id, spec in FORMULA_REGISTRY.items():
        haystack = " ".join([formula_id, spec.task_type, spec.expression, spec.premise]).lower()
        matched = sorted(cue for cue in PATTERN_SHAPED_REGISTRY_CUES if cue in haystack)
        if DATASET_ROW_ID_PATTERN.search(haystack):
            matched.append("dataset_row_id")
        if formula_id in FORMULA_IDS:
            matched.extend(
                f"ambiguous_executable_expression:{cue.strip()}"
                for cue in sorted(AMBIGUOUS_EXECUTABLE_EXPRESSION_CUES)
                if cue in f" {spec.expression.lower()} "
            )
        if not matched:
            continue
        issues.append(
            {
                "formula_id": formula_id,
                "matched_cues": matched,
                "executable": formula_id in FORMULA_IDS,
            }
        )
    return {
        "ok": not issues,
        "issues": issues,
        "checked_formula_count": len(FORMULA_REGISTRY),
        "policy": "registry_cards_must_describe_general_constraints_not_dataset_patterns",
    }
